/**
 * The offline half of [OnlineWatchCache] (round 4): the folder layout in
 * `Download/Langosphere/online/`, the move from the old private location,
 * and the saved copy a clip plays from without the network — all against
 * the real Media3 [SimpleCache] with its in-folder index.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [35])
class OnlineWatchCacheOfflineTest {

    @get:Rule
    val tmp = TemporaryFolder()

    private val videoId = "dQw4w9WgXcQ"
    private val s360 = OnlineStream(url = "https://r1.googlevideo.com/videoplayback?itag=18&sig=a", qualityLabel = "360p", mimeType = "video/mp4", height = 360)
    private val s720 = OnlineStream(url = "https://r1.googlevideo.com/videoplayback?itag=22&sig=b", qualityLabel = "720p", mimeType = "video/mp4", height = 720)
    private val details = OnlineVideoDetails(
        video = OnlineVideo(id = videoId, title = "Never Gonna", author = "Rick", authorId = "UC1", thumbnailUrl = "https://i.ytimg.com/vi/x/hq.jpg", lengthSeconds = 212),
        progressiveStreams = listOf(s360, s720),
        captions = listOf(OnlineCaptionTrack(label = "English", languageCode = "en", url = "https://x/en", autoGenerated = false)),
        instance = OnlineInstance(baseUrl = "https://inv.example", kind = OnlineInstanceKind.INVIDIOUS, enabled = true)
    )

    private fun openCache(dir: File, limit: Long = Long.MAX_VALUE): Pair<SimpleCache, AdjustableLruEvictor> {
        val evictor = AdjustableLruEvictor(limit)
        return SimpleCache(dir, evictor, null, null, false, true) to evictor
    }

    /** Streams [payload] through the cache under [key], reading [upTo] bytes (a partial watch). */
    private fun save(cache: SimpleCache, key: String, payload: ByteArray, upTo: Int = payload.size, upstream: DataSource.Factory = DataSource.Factory { ByteArrayDataSource(payload) }): Int {
        val ds = CacheDataSource.Factory().setCache(cache).setUpstreamDataSourceFactory(upstream).setCacheKeyFactory { key }.createDataSource()
        ds.open(DataSpec(Uri.parse("https://example.com/$key")))
        val buf = ByteArray(8192)
        var got = 0
        while (got < upTo) {
            val n = ds.read(buf, 0, buf.size)
            if (n < 0) break
            got += n
        }
        ds.close()
        return got
    }

    private val offlineUpstream = DataSource.Factory {
        object : DataSource {
            override fun addTransferListener(transferListener: TransferListener) {}
            override fun open(dataSpec: DataSpec): Long = throw IOException("offline")
            override fun read(buffer: ByteArray, offset: Int, length: Int): Int = throw IOException("offline")
            override fun getUri(): Uri? = null
            override fun close() {}
        }
    }

    @Test
    fun `the srt twin of a saved track is plain SubRip`() {
        val srt = OnlineWatchCache.toSrt(
            listOf(
                SubtitleEntry(start = 1.5, end = 3.25, text = " Hello ", language = "en"),
                SubtitleEntry(start = 3661.0, end = 3662.001, text = "Bye", language = "en")
            )
        )
        assertEquals("1\n00:00:01,500 --> 00:00:03,250\nHello\n\n2\n01:01:01,000 --> 01:01:02,001\nBye\n\n", srt)
    }

    @Test
    fun `saving captions also writes the srt twin next to the json`() {
        val dir = tmp.newFolder("caps")
        OnlineWatchCache.saveCaptionsToDir(dir, OnlineWatchCache.SLOT_MAIN, "en", "English", listOf(SubtitleEntry(0.0, 1.0, "a", "en")))
        assertTrue(File(dir, "${OnlineWatchCache.SLOT_MAIN}.json").isFile)
        assertTrue(File(dir, "${OnlineWatchCache.SLOT_MAIN}.srt").readText().startsWith("1\n00:00:00,000 --> 00:00:01,000\na"))
    }

    @Test
    fun `nomedia sits at the folder root only - SimpleCache sweeps strangers out of video`() {
        val root = tmp.newFolder("online")
        OnlineWatchCache.ensureNoMedia(root)
        assertTrue(File(root, ".nomedia").isFile)
        assertFalse(File(root, "video/.nomedia").exists())
    }

    @Test
    fun `a writable folder is probed without leaving anything behind`() {
        val dir = File(tmp.root, "probe/online")
        assertTrue(OnlineWatchCache.isWritableDir(dir))
        assertEquals(0, dir.listFiles()!!.size)
    }

    @Test
    fun `older private data moves to the public folder file by file`() {
        val priv = tmp.newFolder("priv")
        val pub = tmp.newFolder("pub")
        val video = File(priv, "video").apply { mkdirs() }
        File(video, "abc.uid").writeBytes(ByteArray(0))
        File(video, "1.0.1700000000000.v3.exo").writeBytes(ByteArray(5000) { it.toByte() })
        File(priv, "captions/vid1").apply { mkdirs() }.resolve("main.json").writeText("{\"entries\":[]}")
        File(priv, "index.json").writeText("{\"a\":1}")

        assertTrue(OnlineWatchCache.migrate(priv, pub))
        assertTrue(File(pub, "video/abc.uid").isFile)
        assertEquals(4999.toByte(), File(pub, "video/1.0.1700000000000.v3.exo").readBytes()[4999])
        assertEquals("{\"entries\":[]}", File(pub, "captions/vid1/main.json").readText())
        assertEquals("{\"a\":1}", File(pub, "index.json").readText())
        assertFalse(File(priv, "video").exists())
        assertFalse(File(priv, "captions").exists())
        assertFalse(File(priv, "index.json").exists())
        // Nothing left: a second run is a no-op that still says "done".
        assertTrue(OnlineWatchCache.migrate(priv, pub))
    }

    @Test
    fun `a folder whose cache files cannot be touched is left alone`() {
        val root = tmp.newFolder("foreign")
        assertFalse(OnlineWatchCache.hasForeignFiles(root))
        val video = File(root, "video").apply { mkdirs() }
        File(video, "1.0.1.v3.exo").writeBytes(ByteArray(10))
        assertFalse(OnlineWatchCache.hasForeignFiles(root))
        val index = File(video, "cached_content_index.exi").apply { writeBytes(ByteArray(4)) }
        index.setReadable(false)
        index.setWritable(false)
        // (a root user can still read it — then there is nothing to detect)
        if (!index.canRead()) assertTrue(OnlineWatchCache.hasForeignFiles(root))
        index.setReadable(true)
        index.setWritable(true)
    }

    @Test
    fun `the content-range total is read from a ranged response`() {
        val total = ContentLengthRecordingDataSource.contentRangeTotal(mapOf("Content-Range" to listOf("bytes 0-1023/5000")))
        assertEquals(5000L, total)
        assertNull(ContentLengthRecordingDataSource.contentRangeTotal(mapOf("content-range" to listOf("bytes 100-200/*"))))
        assertNull(ContentLengthRecordingDataSource.contentRangeTotal(mapOf("Content-Length" to listOf("5"))))
    }

    @Test
    fun `the in-folder index survives a reopen and a complete copy replays offline`() {
        val dir = tmp.newFolder("c1")
        val key = OnlineWatchCache.streamKey(videoId, s360)
        val payload = ByteArray(300_000) { (it % 251).toByte() }
        var (cache, _) = openCache(dir)
        save(cache, key, payload, upTo = 100_000)
        val partial = cache.getCachedBytes(key, 0, Long.MAX_VALUE)
        assertTrue(partial in 100_000L..300_000L)
        assertEquals(300_000L, ContentMetadata.getContentLength(cache.getContentMetadata(key)))
        cache.release()

        // Reopen: the spans and the known total come back from the folder's own index.
        cache = openCache(dir).first
        assertEquals(partial, cache.getCachedBytes(key, 0, Long.MAX_VALUE))
        assertEquals(300_000L, ContentMetadata.getContentLength(cache.getContentMetadata(key)))
        assertTrue(File(dir, "cached_content_index.exi").isFile)

        // Finish the clip, then play it back with no network at all.
        save(cache, key, payload)
        assertEquals(300_000L, cache.getCachedBytes(key, 0, Long.MAX_VALUE))
        val offline = save(cache, key, payload, upstream = offlineUpstream)
        assertEquals(payload.size, offline)
        cache.release()
    }

    @Test
    fun `lowering the limit trims the least recently used spans at once`() {
        val dir = tmp.newFolder("c2")
        val (cache, evictor) = openCache(dir)
        val key = OnlineWatchCache.streamKey(videoId, s360)
        save(cache, key, ByteArray(300_000) { 1 })
        evictor.maxBytes = 150_000
        synchronized(cache) { evictor.trim(cache) }
        assertTrue(cache.getCachedBytes(key, 0, Long.MAX_VALUE) <= 150_000L)
        cache.release()
    }

    @Test
    fun `the saved copy lists the best-covered rendition first and knows when it is complete`() {
        val dir = tmp.newFolder("c3")
        val (cache, _) = openCache(dir)
        val entry = JSONObject()
        OnlineWatchCache.fillEntry(
            entry, details.video.title,
            listOf(OnlineWatchCache.streamKey(videoId, s360), OnlineWatchCache.streamKey(videoId, s720), OnlineWatchCache.audioKey(videoId)),
            details
        )
        assertNull(OnlineWatchCache.offlineCopyFrom(cache, videoId, entry))

        save(cache, OnlineWatchCache.streamKey(videoId, s720), ByteArray(200_000) { 2 }, upTo = 50_000)
        save(cache, OnlineWatchCache.streamKey(videoId, s360), ByteArray(100_000) { 3 })

        val copy = OnlineWatchCache.offlineCopyFrom(cache, videoId, entry)
        assertNotNull(copy)
        assertTrue(copy!!.offlineCopy)
        assertEquals(OnlineWatchCache.OFFLINE_BASE_URL, copy.instance.baseUrl)
        assertEquals("360p", copy.progressiveStreams.first().qualityLabel)
        assertEquals(s360.url, copy.progressiveStreams.first().url)
        assertTrue(OnlineWatchCache.isComplete(copy.offlineCoverage))
        assertEquals("Never Gonna", copy.video.title)
        assertEquals(212L, copy.video.lengthSeconds)
        assertEquals("en", copy.captions.single().languageCode)

        val only720 = JSONObject()
        OnlineWatchCache.fillEntry(only720, "t", listOf(OnlineWatchCache.streamKey(videoId, s720)), details.copy(progressiveStreams = listOf(s720)))
        val partial = OnlineWatchCache.offlineCopyFrom(cache, videoId, only720)!!
        assertFalse(OnlineWatchCache.isComplete(partial.offlineCoverage))
        assertTrue(partial.offlineCoverage in 0.2f..0.4f)
        cache.release()
    }
}
